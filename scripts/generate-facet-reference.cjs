  InstitutionalOrgRegistryFacet: "Maps normalized organization identifiers to institutions and backend URLs.",
  InstitutionalTreasuryFacet: "Manages institutional backend delegation, limits and treasury spending.",
  LabFacet: "Provides ERC-721 lab ownership, listing and core lab operations.",
  LabAdminFacet: "Creates, updates and administers labs with creator identity checks.",
  LabIntentFacet: "Executes lab administration through registered intents.",
  LabQueryFacet: "Reads lab configuration, availability and paginated lab state.",
  LabReputationFacet: "Reads and updates provider/lab reputation state.",
  ProviderSettlementFacet: "Builds and settles provider receivable claims.",
  InstitutionalReservationRequestValidationFacet: "Validates institutional reservation request constraints.",
  InstitutionalReservationRequestCreationFacet: "Creates pending institutional reservation requests.",
  InstitutionalReservationConfirmationFacet: "Confirms a pending institutional reservation request.",
