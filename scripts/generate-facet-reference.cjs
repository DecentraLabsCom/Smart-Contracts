#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const {Interface} = require("ethers");

const rootDir = path.resolve(__dirname, "..");
const manifestPath = path.join(rootDir, "selectors", "diamond.json");
const abiPath = path.join(rootDir, "abi", "Diamond.json");
const deploymentPath = path.join(rootDir, "deployments", "sepolia-latest.json");
const outputPath = path.join(rootDir, "docs", "reference", "facets.md");

